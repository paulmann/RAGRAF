from ragraf.config import DEFAULT_EXCLUDES, NON_DEFAULT_EXCLUDES  # noqa: E402

SECTION = """

### 8.17 Служебные каталоги: что исключается всегда

**Зачем этот раздел.** Настройка исключений влияет на то, что попадёт в индекс,
но она разнесена по трём местам, и до недавнего времени они расходились.
Корпус, подключённый вручную (не командой `init`), индексировал кеши
и виртуальные окружения — в индексе появлялись тысячи файлов вида
`site-packages/*.py` и `__pycache__/*.pyc`.

**Как устроено сейчас.** Есть базовый список `DEFAULT_EXCLUDES`
(`src/ragraf/config.py`), который применяется ВСЕГДА:

```python
exclude = list(DEFAULT_EXCLUDES) + из_файла_конфига   # config.py
```

То есть правило из конфига корпуса добавляется к базовому, а не заменяет его.
Если правило нужно только одному корпусу — его пишут в конфиг; если всем —
в базовый список.

**Что исключается базово (24 каталога + 4 образца имён):**

| группа | каталоги |
|---|---|
| история и зависимости | `.git`, `node_modules`, `vendor`, `bower_components`, `.nuget`, `packages` |
| служебное RAGRAF и агента | **`.ragraf`**, `.zwork`, `.agents`, `.dev_agent`, `.pi` |
| кеши и окружения | `__pycache__`, `.pytest_cache`, `.mypy_cache`, `.venv`, `venv`, `.idea`, `.vscode`, `coverage`, `TestResults` |
| выход сборки | `var`, `dist`, `build`, `target` |
| образцы имён | `*_bak*`, `*backup*`, `*.min.js`, `*.min.css` |

**`.ragraf` обязателен и не отключается.** Внутри него лежат индекс, ревизии,
журнал расхождений и граф свойств кода. Без этого правила индексация читала бы
собственные базы: индекс попал бы в свой же вход, а каждая переиндексация
порождала бы следующую. Проверено: при выключенном правиле служебные пути
попадают в скан, при включённом — 0 файлов (tools/check_service_excludes.py).

**Чего в базовом списке НЕТ и почему.** `bin`, `cache`, `obj`, `publish`,
`logs`, `storage`, `uploads`, `tmp` — эти имена НЕЛЬЗЯ исключать глобально:
по имени назначение каталога неразличимо, и среди них есть каталоги
с рабочим кодом проекта. Замер:

| каталог | что внутри | почему не исключается |
|---|---|---|
| `bin` | revoap.com: 6 рабочих PHP-скриптов; RdpMON: сборка .NET | в одном проекте код, в другом сборка |
| `obj` | RdpMON: 168 сгенерированных `.cs` | шум, но в другом проекте имя может значить рабочее |
| `publish` | RdpMON: 406 файлов сборки, среди них `.html`/`.css`/`.js` | копии исходников |
| `cache` | revoap.com: 15 файлов кеша | безвредно, но не глобально |

Такие каталоги исключаются **в конфиге конкретного корпуса** — там видно
назначение, и ошибка не задевает другие проекты. В `rdpmon.yaml` это сделано.

**Сопоставление шаблонов РЕГИСТРОЗАВИСИМО.** Это неочевидно, но проверено
вызовом (`tools/check_case_sensitivity.py`):

```
**/cache/**   ловит  src/cache/X.php     но НЕ ловит  src/Cache/X.php
**/bin/**     ловит  bin/cache-purge.php              (и это рабочий скрипт!)
```

Именно поэтому `src/Cache/CacheStatistics.php`, `src/Logs/LogsService.php`
и `src/Storage/*.php` в revoap.com остаются в индексе: их каталоги написаны
с заглавной буквы, и шаблоны в нижнем регистре их не задевают. Это случайное
спасение, а не расчёт — и ещё одна причина не вносить `cache`, `logs`, `bin`
в базовый список.

**Обязательная проверка после правки исключений.** Расширение списка нельзя
делать без замера: ошибка в нём молча выбросит рабочий код из индекса,
и это не будет видно. Порядок:

```powershell
# 1. сколько файлов выпадет по каждому корпусу
python C:\\AutoClaw\\RAGRAF\\tools\\measure_safe_excludes.py

# 2. проверки после правки: число файлов не должно измениться
python C:\\AutoClaw\\RAGRAF\\tests\\test_exclude_defaults.py
python C:\\AutoClaw\\RAGRAF\\tests\\test_exclude_configs.py
```

Первая команда показывает, сколько файлов выпадет при внесении каждого
каталога. Правило простое: если выпадает НОЛЬ файлов во всех корпусах —
исключать безопасно; если хоть один — каталог идёт в конфиг корпуса,
а не в базовый список.

**Что делать при подключении проекта.** `.ragraf` появится в корне проекта
после первой индексации и будет исключён автоматически. Ничего дописывать
не нужно. Если в проекте есть нестандартные служебные каталоги (например
`_cache_v2`), их добавляют в конфиг корпуса — и после этого обязательно
проверяют, сколько файлов выпало.
"""

