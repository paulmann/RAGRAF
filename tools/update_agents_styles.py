"""Обновление системного промпта: операция class_usage и слой стилей.

Что добавляется:
  1. в таблицу «вопрос → операция» раздела 8.3 — строка про классы оформления;
  2. новый подраздел 8.10 про работу с интерфейсом: где класс определён, где
     использован, что расходится.

Правка идемпотентна, файл сохраняется в исходной кодировке и с исходными
переводами строк.
"""

from __future__ import annotations

import pathlib
import shutil
from datetime import datetime

path = pathlib.Path.home() / ".pi" / "agent" / "AGENTS.md"
raw = path.read_bytes()
had_bom = raw.startswith(b"\xef\xbb\xbf")
crlf = b"\r\n" in raw
text = raw.decode("utf-8-sig").replace("\r\n", "\n")

changed = False

# --- 1. Таблица вопросов ------------------------------------------------------
old_table = """   | «Кто и по какому условию получает право» | **`policy_trace`** |"""
new_table = """   | «Кто и по какому условию получает право» | **`policy_trace`** |
   | «Есть ли стиль для этого класса» | **`class_usage`** |
   | «Где ещё используется этот класс» | **`class_usage`** с именем класса |"""
if "class_usage" not in text.split("### 8.4")[0]:
    if old_table in text:
        text = text.replace(old_table, new_table, 1)
        changed = True
        print("таблица вопросов дополнена: class_usage")
    else:
        print("ВНИМАНИЕ: строка таблицы policy_trace не найдена")
else:
    print("таблица вопросов уже дополнена")

# --- 2. Подраздел 8.10 -------------------------------------------------------
new_section = """### 8.10 Работа с интерфейсом и стилями

Перед правкой шаблона, страницы или оформления — проверить класс через
`class_usage`:

```powershell
# Есть ли правило в стилях и где класс используется
python .../ragraf.py -p <конфиг> query class_usage z-agr-card__head

# Все классы, которые используются, но правил в стилях НЕ имеют
python .../ragraf.py -p <конфиг> query class_usage --mode missing

# Классы, описанные в стилях, но нигде не используемые
python .../ragraf.py -p <конфиг> query class_usage --mode unused
```

Ответ содержит **файл и номер строки** и для определения, и для каждого
использования, а поле `status` прямо называет состояние: «описан и используется»,
«только используется: правила в стилях нет», «только описан».

**Почему это обязательно, а не удобно.** Отсутствие правила в стилях не даёт
ошибки: страница отрисуется оформлением браузера по умолчанию и будет работать.
Дефект виден только сопоставлением. На полигоне так нашлись **30 классов
подсистемы agreements**, используемых в разметке внутри PHP без единого правила
в стилях — при том что ни запуск, ни чтение кода этого не показывали.

**Порядок при правке интерфейса:**

1. `class_usage <класс>` — узнать, описан ли класс и где ещё применяется;
2. если статус «правила в стилях нет» — сначала решить, нужен ли стиль, и только
   потом править разметку; иначе страница «работает», но выглядит случайно;
3. перед удалением или переименованием класса — посмотреть список использований:
   их видно с точностью до строки;
4. после правки стилей — `query freshness --force`.

**Границы.** Сопоставление идёт по имени класса, поэтому:
  * классы, добавляемые из JavaScript строками, видны только частично — такие
    места помечены как непокрытые, не додумываются;
  * вычисление применённого оформления (каскад) не делается: проверяется наличие
    правила, а не его действие в браузере;
  * если оформление лежит вне проиндексированных файлов, класс не найдётся —
    тогда путь нужно добавить в `include` конфигурации корпуса.


"""
anchor = "### 8.9 Панель управления"
if "### 8.10" not in text:
    if anchor in text:
        text = text.replace(anchor, new_section + anchor, 1)
        changed = True
        print("добавлен подраздел 8.10 про работу со стилями")
    else:
        # Раздел 8.9 мог быть последним: тогда новый раздел идёт в конец.
        text = text.rstrip() + "\n\n" + new_section
        changed = True
        print("подраздел 8.10 добавлен в конец файла")
else:
    print("подраздел 8.10 уже есть")

if not changed:
    print("\nизменений не требуется")
    raise SystemExit(0)

stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
backup = path.with_name(f"{path.name}.bak.{stamp}-class-usage")
shutil.copy2(path, backup)
print(f"резервная копия: {backup.name}")

payload = text.encode("utf-8")
if had_bom:
    payload = b"\xef\xbb\xbf" + payload
if crlf:
    payload = payload.replace(b"\n", b"\r\n")
path.write_bytes(payload)

check = path.read_bytes()
print(f"записано: {len(check)} байт, BOM={check.startswith(b'\xef\xbb\xbf')}, "
      f"CRLF={b'\r\n' in check}")
print(f"строк: {len(path.read_text(encoding='utf-8-sig').splitlines())}")
