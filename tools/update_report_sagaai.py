"""Дополнение отчёта: корпус sagaai и разбор Python.

Не хватает двух вещей:
  1. строки корпуса sagaai в таблице (якорь не совпал из-за выделения
     жирным в строке RdpMON);
  2. раздела о поддержке Python — она появилась в этой работе и содержит
     важные ограничения, которые нельзя умалчивать.

Ограничения записываются честно: граф вызовов по Python построен частично,
поэтому часть операций работает неполно. Это не «не получилось», а
измеренное состояние с указанием причины.
"""

from __future__ import annotations

import pathlib

REPO = pathlib.Path(__file__).resolve().parents[1]
TARGET = REPO / "docs" / "RAGRAF-REPORT.md"
text = TARGET.read_text(encoding="utf-8")
before_lines = len(text.splitlines())
changes: list[str] = []

# --- 1. Строка корпуса sagaai ---
if "| sagaai |" not in text:
    anchor = "| **RdpMON** | rev-0006 | 1266 | 20131 | 97041 |"
    idx = text.find(anchor)
    if idx >= 0:
        end = text.find("\n", idx)
        row = ("\n| **sagaai** | rev-0008 | 378 | 5751 | 34779 | "
               "python 271, markdown 74, json 29, ini 1, text 1, xml 1 |")
        text = text[:end] + row + text[end:]
        changes.append("добавлена строка корпуса sagaai")
    else:
        changes.append("ОШИБКА: строка RdpMON не найдена")

# --- 2. Раздел о разборе Python ---
MARKER = "## Разбор Python: что заработало и что нет"
if MARKER not in text:
    section = """
## Разбор Python: что заработало и что нет

Корпус sagaai (Python/Streamlit) стал первым корпусом этого языка.
Разбор потребовал правок, и часть ограничений сохраняется — они указаны
прямо, чтобы ими не пользовались вслепую.

### Что заработало

| Возможность | Состояние | Замер |
|---|---|---|
| Разбор исходников деревом | работает | 378 файлов, 5751 узел |
| Дерево символов (функции, классы) | работает | 3362 функции, 730 методов, 192 класса |
| Поиск по коду и смыслу | работает | возвращает пути и строки |
| Роли документов | работает | правила агента опознаются |
| Рёбра вызовов разбором дерева | работает | 22 886 (`calls_heuristic`) |
| Рёбра вызовов из графа Joern | работает | 4299 (`calls`) |

### Правки, которые для этого понадобились

1. **Выбор языка.** В сборке графа было жёстко зашито `--language PHP`.
   Для Python используется отдельный парсер Joern `pysrc2cpg`, который
   нашёлся в установке (`.bat`-обёртка) и умеет `--ignore-dir-names`.
2. **Исключения служебных каталогов.** Передача списка в `--ignore-dir-names`
   требует **кавычек** вокруг значения: без них cmd.exe разбирает запятую
   как разделитель аргументов, и Joern отвечает «Unknown argument».
   Ошибка была неочевидной: код возврата 1 без указания на кавычки.
3. **Нормализация имён.** Правило приведения имён было написано под PHP
   (`->` → `::`). Для Python оно портило имя: `core\\api_errors.py:__init__`
   не совпадало ни с одним полным именем индекса. Добавлено отдельное
   правило: разделители пути приводятся к прямым слешам, форма `путь:имя`
   сохраняется.
4. **Обозначение глобальной области.** У PHP это `<global>`, у Python —
   `<module>`. Проверялось только первое, поэтому вызовы уровня модуля
   не отсеивались и одновременно не привязывались.

### Сохраняющиеся ограничения

1. **Экспорт графа Python падает.** `joern-export` завершается ошибкой
   `SchemaViolationException: OUT edge with label REF to an adjacent METHOD
   is mandatory, but not defined for this METHOD_REF node`. Падение
   происходит при расчёте оверлея потока данных, а не при выгрузке:
   сам граф пригоден. Проверено на всех сочетаниях `--repr` и `--format` —
   не работает ни одно.
2. **Серверный путь недоступен.** Оба способа получить граф через сервер
   Joern для Python падают:
   * `importCode` ищет исполняемый генератор `pysrc2cpg` и не находит его
     (в установке только `.bat`-обёртка);
   * `importCpg` падает с `NullPointerException` в `XTypeRecoveryPassGenerator`.
3. **Вызовы уровня модуля не привязываются.** Joern для Python помечает
   владельцем `<module>` даже внутри функций (замер: все 172 184 записи),
   поэтому привязка идёт в основном по разбору деревом.
4. **Операции `slice` и полный `impact` недоступны** для этого корпуса:
   они требуют графа свойств кода. `impact` отвечает, но по неполным данным.

### Как это влияет на работу

Для поиска по коду, навигации по символам и понимания структуры корпуса
sagaai пригоден: эти операции опираются на разбор деревом и работают.
Для анализа потока данных и точной оценки последствий правки — нет:
там нужен настоящий CPG, а он для Python не выгружается.

"""
    anchors = ["\n## 4.", "\n## 5.", "\n## Учёт агента в статистике"]
    inserted = False
    for anchor in anchors:
        if anchor in text:
            text = text.replace(anchor, section + anchor, 1)
            changes.append(f"добавлен раздел о разборе Python (перед {anchor.strip()})")
            inserted = True
            break
    if not inserted:
        text = text.rstrip() + "\n" + section
        changes.append("добавлен раздел о разборе Python (в конец)")

TARGET.write_text(text, encoding="utf-8", newline="\n")
after = TARGET.read_text(encoding="utf-8")
print(f"  строк: было {before_lines}, стало {len(after.splitlines())}")
print()
print("  изменения:")
for c in changes:
    print(f"    - {c}")

print()
print("  проверки:")
checks = [
    ("| **sagaai** | rev-0008 |" in after, "корпус sagaai в таблице"),
    (MARKER in after, "раздел о разборе Python добавлен"),
    (after.count(MARKER) == 1, "раздел ровно один"),
    ("pysrc2cpg" in after, "упомянут парсер Python"),
    ("SchemaViolationException" in after, "указана причина отказа экспорта"),
    ("ограничения" in after.lower(), "ограничения записаны"),
    ("rev-0155" in after, "номер ревизии z актуален"),
]
for ok, label in checks:
    print(f"    [{'OK ' if ok else '--'}] {label}")
