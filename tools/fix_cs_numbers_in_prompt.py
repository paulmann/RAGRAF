"""Уточнение чисел C# в промпте: всего против проиндексировано.

Проверка выявила расхождение: в промпте стояло «1217 файлов .cs», а в индексе
их 1164. Оба числа верны, но означают разное, и агент, прочитав только одно,
получит неверную картину.

Замер (выполнен здесь же):
    всего .cs в 1st_RdpMON\\Service:           1385
    из них в .zwork (служебный агента):             53
    из них в obj (сгенерированные сборкой):        168
    попадает в индекс:                            1164

Проверка: 1385 - 53 - 168 = 1164. Сходится.

Число 1217 было получено раньше, при первом сканировании, с другим набором
исключений (исключался publish). Оно тоже верно, но контекст другой, и в
промпте рядом с «основной язык проекта» оно читается как «столько в индексе».
Поэтому оно заменяется на пару чисел с явным пояснением.
"""

from __future__ import annotations

import pathlib

PROMPT = pathlib.Path.home() / ".pi/agent/AGENTS.md"
RAGRAF_PROMPT = pathlib.Path(
    str(pathlib.Path(__file__).resolve().parents[1] / ".staging/AGENTS_updates")
)

OLD = """**Самое дорогое следствие:** в `1st_RdpMON\\Service` 1217 файлов `.cs` —
это основной язык проекта. RAGRAF не мог ответить ни на один вопрос о его
коде: `symbol`, `callers`, `code` возвращали пусто. Инструмент был бесполезен
ровно там, где нужен больше всего."""

NEW = """**Самое дорогое следствие:** в `1st_RdpMON\\Service` 1385 файлов `.cs` —
это основной язык проекта. RAGRAF не мог ответить ни на один вопрос о его
коде: `symbol`, `callers`, `code` возвращали пусто. Инструмент был бесполезен
ровно там, где нужен больше всего.

Разница между «файлов в проекте» и «файлов в индексе» здесь существенная,
и её надо видеть: из 1385 файлов .cs в индекс попадает 1164. Остальные 221
отсекают исключения — 53 файла лежат в `.zwork` (служебный каталог агента),
168 в `obj` (сгенерированные сборкой файлы вида AssemblyInfo.cs). Это не
потеря исходников, а отсев сопровождения. Тот же порядок действует в любом
корпусе: сравнивать числа нужно при одинаковых исключениях."""

text = PROMPT.read_text(encoding="utf-8")
if OLD not in text:
    if "1385 файлов `.cs`" in text:
        print("уже уточнено ранее — правка не нужна")
    else:
        raise SystemExit("НЕ НАЙДЕН фрагмент для замены")
else:
    text = text.replace(OLD, NEW, 1)
    PROMPT.write_text(text, encoding="utf-8", newline="\n")
    print("числа C# уточнены")

after = PROMPT.read_text(encoding="utf-8")
print(f"  размер: {len(after.encode('utf-8'))} байт, строк {after.count(chr(10)) + 1}")
for number, what in (("1385", "всего .cs в проекте"),
                     ("1164", "в индексе"),
                     ("53", "в .zwork"),
                     ("168", "в obj")):
    print(f"  {number:<6} ({what}): {'есть' if number in after else 'НЕТ'}")

# Контрольная арифметика: числа должны сходиться.
print(f"\n  проверка: 1385 - 53 - 168 = {1385 - 53 - 168}  (ожидается 1164)")
assert 1385 - 53 - 168 == 1164, "арифметика не сходится"
print("  сходится")
