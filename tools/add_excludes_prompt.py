for probe, expected in checks:
    present = probe in final
    status = "есть" if present else "НЕТ"
    ok = present == expected
    print(f"  {probe[:34]:<36} {status} {'верно' if ok else 'ОШИБКА'}")

# Проверка: опасные каталоги названы как «не в базовом списке».
