"""Обновление системного промпта: подключение нового проекта к RAGRAF.

Что добавляется:
  1. в раздел 8.2 — строка про проверку наличия корпуса в самом начале;
  2. новый подраздел 8.5 (переписанный): полная процедура подключения нового
     проекта, включая создание конфигурации командой init.

Причина правки: агент MD.Viewer отрапортовал, что не смог воспользоваться
RAGRAF. Разбор показал, что процедура подключения нового проекта была
замкнутым кругом: `register` требует конфиг, а команды создать конфиг не было.
Теперь такая команда есть (`init`), и промпт должен её называть.

Правка идемпотентна; кодировка и переводы строк сохраняются.
"""

from __future__ import annotations

import pathlib
import shutil
from datetime import datetime

path = pathlib.Path.home() / ".pi" / "agent" / "AGENTS.md"
raw = path.read_bytes()
had_bom = raw.startswith(b"\xef\xbb\xbf")
crlf = b"\r\n" in raw
text = raw.decode("utf-8-sig").replace("\r\n", "\n")
changed = False

# --- 1. Раздел 8.5: полная процедура подключения нового проекта --------------
old_85_start = "### 8.5 Порядок при недоступности индекса"
old_85_end = "### 8.6"
i = text.find(old_85_start)
j = text.find(old_85_end, i) if i >= 0 else -1

new_85 = """### 8.5 Подключение нового проекта (обязательный порядок)

**Это первый шаг, если проекта ещё нет в RAGRAF.** Проверить наличие:

```powershell
python C:\\AutoClaw\\RAGRAF\\tools\\ragraf.py catalog
```

Если проекта в списке нет — его надо подключить. Порядок:

**Шаг 1. Создать конфигурацию корпуса.**

```powershell
python C:\\AutoClaw\\RAGRAF\\tools\\ragraf.py init C:\\путь\\к\\проекту
```

Команда осматривает каталог и сама собирает конфигурацию: определяет языки
по расширениям, исключает зависимости и сборку, находит файлы с секретами,
подбирает пороги авто-реиндексации по размеру корпуса. **Это единственная
команда, которая работает без `--project`** — она его и создаёт.

**Шаг 2. Проверить список исключений.** Открыть созданный файл (путь печатает
команда) и убедиться, что в индекс не попадут:

* зависимости (`vendor`, `node_modules`) — иначе индекс забьётся чужим кодом;
* собранные файлы (`dist`, `build`) — они дублируют исходники;
* каталоги с секретами (`config.local.*`, `.env`, ключи) — они не должны
  индексироваться и попадать в ответы.

**Шаг 3. Зарегистрировать и проиндексировать.**

```powershell
python C:\\AutoClaw\\RAGRAF\\tools\\ragraf.py -p <путь к конфигу> register
python C:\\AutoClaw\\RAGRAF\\tools\\ragraf.py -p <путь к конфигу> index
```

Индексация печатает: число файлов, узлов, рёбер, чанков и разбивку по языкам.
Проверить, что ожидаемые языки на месте: если чего-то не хватает, значит
расширение не попало в список `include`.

**Шаг 4. Убедиться, что индекс отвечает.** Выполнить одну операцию по известному
имени файла или функции:

```powershell
python C:\\AutoClaw\\RAGRAF\\tools\\ragraf.py -p <путь к конфигу> query search "имя функции"
```

Если поиск находит файлы — корпус подключён и дальнейшая работа идёт через RAGRAF.

### Порядок при недоступности индекса

Если индекс не создан или сломан (`capability: degraded`), это не повод молча
работать по памяти. Нужно:

1. проверить, есть ли проект в реестре: `ragraf catalog`;
2. если нет — подключить по порядку выше (`init` → `register` → `index`);
3. если индексация невозможна (нет зависимостей, нет прав), **прямо сказать
   об этом** и работать чтением файлов, отметив в отчёте, что факты
   не подтверждены индексом.

"""

if i >= 0 and j > i:
    text = text[:i] + new_85 + text[j:]
    changed = True
    print("раздел 8.5 переписан: полная процедура подключения проекта")
else:
    print("ВНИМАНИЕ: раздел 8.5 не найден")

# --- 2. Раздел 8.2: проверка наличия корпуса первым делом -------------------
old_82 = """### 8.2 Первый шаг задачи на разработку — проверка свежести

**Перед первым обращением к коду проекта RAGRAF сам сверяет контрольную сумму
корпуса.**"""
new_82 = """### 8.2 Первый шаг задачи на разработку

**Сначала проверить, подключён ли проект к RAGRAF:**

```powershell
python C:\\AutoClaw\\RAGRAF\\tools\\ragraf.py catalog
```

Если проекта нет в списке — его надо подключить: порядок в разделе 8.5.
**Не начинать работу с чтения файлов, не проверив это:** иначе индекс
не будет использован вообще, и вся дальнейшая работа пойдёт по памяти.

**Если проект подключён — перед первым обращением к коду RAGRAF сам сверяет
контрольную сумму корпуса.**"""
if old_82 in text:
    text = text.replace(old_82, new_82, 1)
    changed = True
    print("раздел 8.2 дополнен проверкой наличия корпуса")
else:
    print("ВНИМАНИЕ: начало раздела 8.2 не найдено")

if not changed:
    print("\nизменений не требуется")
    raise SystemExit(0)

stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
backup = path.with_name(f"{path.name}.bak.{stamp}-init")
shutil.copy2(path, backup)
print(f"резервная копия: {backup.name}")

payload = text.encode("utf-8")
if had_bom:
    payload = b"\xef\xbb\xbf" + payload
if crlf:
    payload = payload.replace(b"\n", b"\r\n")
path.write_bytes(payload)
print(f"записано: {len(payload)} байт, строк "
      f"{len(path.read_text(encoding='utf-8-sig').splitlines())}")
