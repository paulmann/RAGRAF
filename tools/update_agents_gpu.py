"""Добавление в системный промпт раздела о видеокарте.

Что добавляется:
  * в таблицу «вопрос → операция» — строка про состояние вычислителя;
  * новый подраздел 8.11 про видеокарту: где она помогает, где нет,
    почему порог окупаемости важен и как его менять.

Правка идемпотентна; кодировка и переводы строк сохраняются.
"""

from __future__ import annotations

import pathlib
import shutil
from datetime import datetime

path = pathlib.Path.home() / ".pi" / "agent" / "AGENTS.md"
raw = path.read_bytes()
had_bom = raw.startswith(b"\xef\xbb\xbf")
crlf = b"\r\n" in raw
text = raw.decode("utf-8-sig").replace("\r\n", "\n")
changed = False

# --- 1. Таблица вопросов ---
old_row = """   | «Есть ли стиль для этого класса» | **`class_usage`** |"""
new_row = """   | «Есть ли стиль для этого класса» | **`class_usage`** |
   | «Где считаются векторы и почему» | `index_status`, блок `quality.compute` |"""
if "quality.compute" not in text:
    if old_row in text:
        text = text.replace(old_row, new_row, 1)
        changed = True
        print("таблица вопросов дополнена: состояние вычислителя")
    else:
        print("ВНИМАНИЕ: строка таблицы class_usage не найдена")
else:
    print("таблица вопросов уже дополнена")

# --- 2. Подраздел о видеокарте ---
section = """### 8.11 Видеокарта: где она помогает, а где нет

Кодирование текста в векторы выполняется на видеокарте, когда её работа
окупается. Остальные участки индексации считаются на процессоре, и это не
недоделка, а результат замеров — не надо пытаться их «ускорить картой».

| Участок | Видеокарта | Почему |
|---|---|---|
| Кодирование текста в векторы | **ДА, до 47×** | матричные операции нейросети |
| Граф свойств кода (Joern) | НЕТ | это Java-программа, CUDA не использует |
| Разбор дерева (tree-sitter) | НЕТ | последовательный разбор текста |
| Сравнение векторов при поиске | НЕТ | 0,09 мс — дешевле передачи данных на карту |
| Обход файлов, запись в базы | НЕТ | это ввод-вывод |
| Схема БД из миграций | НЕТ | разбор текста |

**Порог окупаемости — почему карта не включается всегда.** Подготовка
видеокарты под архитектуру sm_120 занимает около **26 секунд** разово на запуск
процесса (из них 15 с — первый проход модели). Само кодирование на карте
быстрее процессора в 38–47 раз, но на малом объёме работы подготовка не
окупается.

Точка равенства по замерам — **1451 текст**. Порог по умолчанию 1800 с запасом.

Что это значит на практике:

* при **полной индексации крупного корпуса** (тысячи текстов) карта выгодна:
  на пилоте индексация сократилась со 143,7 с до 101,6 с;
* при **быстрой переиндексации после правки файла** новых текстов единицы,
  поэтому считается на процессоре — это правильное поведение;
* на корпусе `z.batteryservice.ru` (около 1078 новых векторов при полной
  индексации) карта не включается: по порогу она проиграла бы 6,5 с.

**Где смотреть состояние.** Блок `quality.compute` в `index_status` показывает:
где считаются векторы (`backend`), на каком устройстве (`device`), почему выбран
этот путь (`reason`), сколько миллисекунд на текст и сколько свободно на карте.

**Как менять.** В панели управления: `use_gpu` (включить/выключить), `gpu_min_texts`
(порог окупаемости), `gpu_batch_size` (партия). В конфиге корпуса — `device`:
`auto`, `cpu` или `cuda:0`.

**Чего агент делать НЕ должен:**

* пытаться ускорить граф свойств кода через видеокарту: это Java-программа;
* понижать порог «чтобы карта работала»: на малом объёме это замедляет работу;
* ожидать ускорения всей индексации в разы: карта ускоряет только стадию
  векторов, а построение графа свойств кода остаётся на процессоре.


"""
anchor = "### 8.9 Работа с интерфейсом"
if "### 8.11" not in text:
    if anchor in text:
        text = text.replace(anchor, section + anchor, 1)
        changed = True
        print("добавлен подраздел о видеокарте перед разделом 8.9")
    else:
        text = text.rstrip() + "\n\n" + section
        changed = True
        print("подраздел о видеокарте добавлен в конец")
else:
    print("подраздел о видеокарте уже есть")

if not changed:
    print("\nизменений не требуется")
    raise SystemExit(0)

stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
backup = path.with_name(f"{path.name}.bak.{stamp}-gpu")
shutil.copy2(path, backup)
print(f"резервная копия: {backup.name}")

payload = text.encode("utf-8")
if had_bom:
    payload = b"\xef\xbb\xbf" + payload
if crlf:
    payload = payload.replace(b"\n", b"\r\n")
path.write_bytes(payload)
print(f"записано: {len(payload)} байт, строк "
      f"{len(path.read_text(encoding='utf-8-sig').splitlines())}")
