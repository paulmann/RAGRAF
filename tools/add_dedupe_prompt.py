"""Обновление системного промпта: раздел о схлопывании дублей.

Зачем. Возможность меняет СОСТАВ индекса, и агент обязан знать о ней по
двум причинам:

 1. Числа в отчётах станут другими. В revoap файлов было 699, стало 592.
    Агент, сверив отчёт с индексом и увидев расхождение, решит, что файлы
    потеряны — хотя это работающая настройка.

 2. Правило «схлопывать по хэшу, а не по имени» записано в разделе 8.15 как
    предписание на будущее. Теперь оно реализовано, и предписание надо
    заменить описанием работающего механизма, иначе промпт будет врать.

Что добавляется: раздел 8.16 с настройками, числами замеров, правилом выбора
главной копии и честной оговоркой о том, что файлы на диске не удаляются.

Правка идёт скриптом: прямой доступ к файлу закрыт (он вне рабочего каталога).
Скрипт идемпотентен.
"""

from __future__ import annotations

import pathlib
import shutil

TARGET = pathlib.Path(r"C:\Users\mvd.AMD5700X3D\.pi\agent\AGENTS.md")
BACKUP = TARGET.with_suffix(".md.bak-dedupe")

SECTION = """

### 8.16 Схлопывание дублей документации

**Задача.** В каталогах разработки один и тот же документ лежит десятками
копий. Замер по `C:\\AutoClaw`: 5559 документов дали **513 групп копий
и 3856 лишних файлов** — 44,7 МБ против 2,3 МБ полезного текста. Худший
случай — один ADR в 104 копиях, размноженный вложением каталогов
(`old/revoap.com/www/www/www/www/docs/`).

**Последствие для поиска.** Каждая копия даёт свои чанки, свои векторы и свой
текст в полнотекстовом поиске: один текст обрабатывается десятки раз, а выдача
заполняется его же копиями. Агент видит десять «разных» результатов вместо
одного.

**Что сделано.** Файлы группируются по `sha256` (он считается при
сканировании). Из каждой группы остаётся одна «главная» копия, остальные
в индекс не идут.

**Файлы на диске НЕ удаляются.** Инструмент только перестаёт считать копии
отдельными сущностями индекса. Удаление — необратимая операция, и решать её
должен владелец, а не индексатор.

**Сравнение по содержимому, а не по имени.** Из 120 файлов `readme.md`
в `C:\\AutoClaw` **103 имеют разное содержимое** — схлопывание по имени слило
бы разные документы в один. Контрольная сумма этого не допустит.

**Настройки** (панель администратора, раздел настроек индекса):

| настройка | значения | смысл |
|---|---|---|
| `dedupe_enabled` | да/нет | включить схлопывание; **по умолчанию выключено** |
| `dedupe_scope` | `docs` \\| `all` | что схлопывать: только документы или все файлы |
| `dedupe_mode` | `keep_one` \\| `skip_all` | оставить одну копию или не индексировать ни одной |
| `dedupe_keep` | `cleanest` \\| `shortest` \\| `longest` \\| `newest` | какую копию считать главной |
| `dedupe_report` | да/нет | показывать разбор групп в ответе операции |

**Почему правило по умолчанию — `cleanest`.** Проверены четыре правила
на 513 реальных группах (`tools/measure_dedupe_rules.py`). Считалось, сколько
групп получило «главным» путь из каталога-копии (сегменты `backup`, `old`,
`publish`, `release`, `out`, `copy`, `www`, `_to.upload`, `verify`):

```
без мусорных сегментов   38   ← выбрано
самый свежий             65
самый короткий           76
самый длинный           242
```

Выбор **детерминирован**: при полном равенстве берётся лексикографически
первый путь. Это обязательное условие, а не мелочь: если выбор зависит от
порядка обхода каталога, то главным при каждом сканировании станет разный
файл, сумма корпуса изменится, и сторож свежести начнёт запускать
переиндексацию бесконечно.

**Что видно в ответе операции.** Схлопывание не скрыто — числа попадают
в `index_status`:

```json
{
  "files_found": 699,
  "files_total": 592,
  "dup_dropped": 107,
  "dup_groups": 86,
  "dup_bytes": 17440,
  "dup_lines": 549
}
```

`files_found` — сколько нашлось на диске, `files_total` — сколько попало
в индекс, `dup_dropped` — сколько копий отброшено. Если `dup_dropped` больше
нуля, разница между первым и вторым числом объясняется схлопыванием,
а не потерей файлов.

**Проверено на корпусе revoap.com.** Было 699 файлов, стало 592; отброшено
107 копий (86 групп); все они — документы в `deploy/host/state`, файлы кода
не затронуты (0 из 107). В выдаче поиска путей-копий нет. Сторож свежести
не зацикливается: сумма корпуса считается по оставленным файлам и совпадает
с записанной в ревизии.

**Важно про выключенное состояние.** По умолчанию схлопывание выключено,
и это осознанно: его включение меняет состав индекса, то есть требует
переиндексации и сдвигает все числа в отчётах. Включать его следует тогда,
когда дубли мешают, а не «на всякий случай».

**Что делать при подключении нового проекта.** Сначала посмотреть, есть ли
дубли, отдельным замером (в корпусе z.batteryservice.ru, RdpMON и MD.Viewer
их нет вовсе, в revoap.com было 107). Включать схлопывание при нуле дублей
бессмысленно: появится только лишняя настройка и изменится сумма корпуса.
"""

text = TARGET.read_text(encoding="utf-8")

if "### 8.16" in text:
    print("раздел 8.16 уже есть — правка не нужна")
else:
    if not BACKUP.exists():
        shutil.copy2(TARGET, BACKUP)
        print(f"резервная копия: {BACKUP.name}")
    text = text.rstrip() + "\n" + SECTION
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("раздел 8.16 добавлен")

# Отдельно: в разделе 8.15 правило про дубли было предписанием на будущее.
# Теперь оно реализовано, и формулировку надо привести в соответствие —
# иначе промпт будет описывать несделанную работу как планируемую.
text = TARGET.read_text(encoding="utf-8")
OLD_815 = """**Дубликаты документации.** Разведка нашла 669 побайтово одинаковых копий
(зеркала каталогов, копии сборки). Схлопывать их надо **по хэшу содержимого,
а не по имени**: из 120 файлов `readme.md` 103 имеют разное содержимое.
Схлопывание по имени слило бы разные документы в один."""
NEW_815 = """**Дубликаты документации.** Разведка нашла побайтово одинаковые копии
(зеркала каталогов, копии сборки). Схлопывать их надо **по хэшу содержимого,
а не по имени**: из 120 файлов `readme.md` 103 имеют разное содержимое.
Схлопывание по имени слило бы разные документы в один. Это правило
**реализовано** — настройки и замеры в разделе 8.16."""

if OLD_815 in text:
    text = text.replace(OLD_815, NEW_815, 1)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("раздел 8.15 приведён в соответствие с реализацией")
elif "реализовано** — настройки и замеры в разделе 8.16" in text:
    print("раздел 8.15 уже обновлён")
else:
    print("ВНИМАНИЕ: абзац про дубликаты в 8.15 не найден")

final = TARGET.read_text(encoding="utf-8")
print()
print(f"  размер: {len(final.encode('utf-8'))} байт, строк {final.count(chr(10)) + 1}")
print(f"  раздел 8.16: {'есть' if '### 8.16' in final else 'НЕТ'}")
for probe in ("3856", "cleanest", "dedupe_enabled", "files_found",
              "НЕ удаляются", "детерминирован"):
    print(f"  {probe!r}: {'есть' if probe in final else 'НЕТ'}")
