"""Уточнение порога окупаемости по РЕАЛЬНОЙ индексации.

Противоречие, которое надо разрешить:
  * изолированный замер с ПРОГРЕВОМ: видеокарта 0,51 с против 19,53 с
    на процессоре — ускорение 38 раз;
  * реальная индексация корпуса: стадия векторов 27,4 с с видеокартой
    против 20,8 с без неё — видеокарта МЕДЛЕННЕЕ.

Причина: в изолированном замере модель была уже загружена и подготовлена,
поэтому разовые расходы не попали в замер. При реальной индексации процесс
запускается заново, и платится ВСЯ разовая цена:
    импорт torch                    1,8 с
    импорт sentence-transformers    4,7 с
    чтение весов модели             4,1 с
    подготовка видеокарты          15,1 с
    ─────────────────────────────────────
    итого                         ~25,7 с

Эти 25,7 с и есть настоящий порог: чтобы видеокарта окупилась, экономия
на кодировании должна их перекрыть. Считается точно из замеров.
"""

from __future__ import annotations

print("=" * 78)
print("УТОЧНЕНИЕ ПОРОГА ОКУПАЕМОСТИ")
print("=" * 78)

# Замеры реальной индексации корпуса z.batteryservice.ru (1078 новых векторов).
real_cpu_lexvec = 20.82    # секунд, стадия векторов на процессоре
real_gpu_lexvec = 27.37    # секунд, стадия векторов на видеокарте
texts = 1078

print(f"\nФакт реальной индексации ({texts} новых векторов):")
print(f"  процессор: {real_cpu_lexvec:.2f} с")
print(f"  видеокарта: {real_gpu_lexvec:.2f} с")
print(f"  видеокарта дороже на {real_gpu_lexvec - real_cpu_lexvec:.2f} с")

# Скорости самого кодирования из изолированных замеров.
cpu_ms = 17.9     # мс на текст (ONNX на процессоре)
gpu_ms = 0.35     # мс на текст (torch на видеокарте)

# Накладные расходы: находятся из факта.
#   стадия_векторов = накладные + текстов * скорость_кодирования
# Отсюда накладные для каждого вычислителя.
cpu_other = real_cpu_lexvec - texts * cpu_ms / 1000
gpu_startup = real_gpu_lexvec - texts * gpu_ms / 1000

print(f"\nРазложение (по замеренным скоростям кодирования):")
print(f"  процессор: кодирование {texts * cpu_ms / 1000:.2f} с, "
      f"прочее {cpu_other:.2f} с")
print(f"  видеокарта: кодирование {texts * gpu_ms / 1000:.2f} с, "
      f"РАЗОВАЯ ПОДГОТОВКА {gpu_startup:.2f} с")

# Точка равенства: где время совпадает.
#   cpu_other + N * cpu_ms/1000 = gpu_startup + N * gpu_ms/1000
threshold = (gpu_startup - cpu_other) / (cpu_ms - gpu_ms) * 1000
print(f"\nТочка равенства: {threshold:.0f} текстов")

print()
print("=" * 78)
print("ТАБЛИЦА ПРИ РАЗНОМ ОБЪЁМЕ РАБОТЫ")
print("=" * 78)
print(f"  {'текстов':>8} {'CPU, с':>9} {'GPU, с':>9} {'разница':>10}  вывод")
print("  " + "-" * 56)
for n in (500, 1078, 1500, 2000, 3000, 4056, 8000, 20000, 50000):
    cpu_s = cpu_other + n * cpu_ms / 1000
    gpu_s = gpu_startup + n * gpu_ms / 1000
    diff = cpu_s - gpu_s
    verdict = "видеокарта выгодна" if diff > 0 else "видеокарта дороже"
    print(f"  {n:>8} {cpu_s:>9.1f} {gpu_s:>9.1f} {diff:>+10.1f}  {verdict}")

print()
print("=" * 78)
print("ВЫВОД ДЛЯ НАСТРОЕК")
print("=" * 78)
# Порог округляется вверх с запасом: на границе не должно быть проигрыша.
safe_threshold = int(threshold / 100 * 115) // 100 * 100 + 200
print(f"""
  Точка равенства: {threshold:.0f} текстов.
  Это значит: видеокарта выгодна не «вообще», а начиная с примерно
  {threshold:.0f} новых текстов в одном запуске.

  Текущие корпуса:
    * z.batteryservice.ru — около {texts} новых векторов при полной индексации,
      а при обычной правке МЕНЬШЕ (остальное переиспользуется). Значит на нём
      видеокарта чаще всего НЕ выгодна;
    * revoap.com — около 4000 векторов при полной индексации. На нём
      видеокарта выгодна.

  Отсюда два следствия для кода:
    1. порог надо поднять с 1000 до {safe_threshold} — тогда видеокарта
       включается только когда она действительно быстрее;
    2. при быстрой переиндексации (после правки файла) новых текстов обычно
       немного, и вычислитель сам останется процессорным — это правильное
       поведение, а не недоработка.

  ЧЕСТНАЯ ОГОВОРКА: прежний порог 1000 был получен из изолированного замера
  с прогретой моделью. Он не учитывал разовые 25 с, и на реальной индексации
  видеокарта проигрывала 6,5 с. Ошибка найдена сравнением с реальной
  индексацией, а не тестом.
""")
