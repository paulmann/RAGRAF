"""Обновление раздела 8 системного промпта: новые операции и пороги.

Что добавляется:
  1. в таблицу «вопрос → операция» — строка про трассировку прав (policy_trace)
     и про режимы table_usage (read/write);
  2. новый подраздел 8.7 про накопление правок на длинных сессиях: агент должен
     знать, что переиндексация бывает быстрой и полной, и почему;
  3. новый подраздел 8.8 про панель управления: где смотреть размеры баз,
     статистику и менять пороги.

Правка идемпотентна: повторный запуск ничего не меняет.
Файл сохраняется с исходной кодировкой и переводами строк.
"""

from __future__ import annotations

import pathlib
import shutil
import sys
from datetime import datetime

path = pathlib.Path.home() / ".pi" / "agent" / "AGENTS.md"
if not path.exists():
    print(f"файл не найден: {path}")
    raise SystemExit(1)

original_bytes = path.read_bytes()
text = original_bytes.decode("utf-8")
had_bom = original_bytes.startswith(b"\xef\xbb\xbf")
crlf = b"\r\n" in original_bytes
print(f"исходник: {len(text)} символов, BOM={had_bom}, CRLF={crlf}")

changed = False

# --- 1. Таблица «вопрос → операция»: новые строки -----------------------------
old_table = """   | «Что в таблице и кто её использует» | `schema`, `table_usage` |
   | «Можно ли так записать» | **`write_check`** |"""
new_table = """   | «Что в таблице и кто её использует» | `schema`, `table_usage` |
   | «Где идёт запись в таблицу» | `table_usage` с `--mode write` |
   | «Кто и по какому условию получает право» | **`policy_trace`** |
   | «Можно ли так записать» | **`write_check`** |"""
if "policy_trace" not in text:
    if old_table in text:
        text = text.replace(old_table, new_table, 1)
        changed = True
        print("таблица вопросов дополнена: policy_trace и режим write")
    else:
        print("ВНИМАНИЕ: таблица вопросов не найдена в ожидаемом виде")
else:
    print("таблица вопросов уже дополнена")

# --- 2. Подраздел про трассировку прав ---------------------------------------
anchor_86 = "### 8.6"
new_section = """### 8.7 Трассировка решений о правах (обязательная проверка)

Перед правкой матрицы прав, маршрута согласования или условия доступа —
`policy_trace`:

```powershell
python .../ragraf.py -p <конфиг> query policy_trace z_agr_can_act
python .../ragraf.py -p <конфиг> query policy_trace z_agr_can_act --operation mark_paid
```

Операция показывает: где функция возвращает разрешение и где отказ, какая ветвь
`case` относится к какому действию, какие точки кода её вызывают и что происходит,
если действие не описано явно.

**Красный флаг.** `default_behavior: allow` означает, что неизвестное действие
получает право. Это дефект, а не проектное решение: проверка обязана отказывать,
когда правило не найдено. На полигоне именно так роль `employee` получила
`approve`, `mark_paid`, `sign` и `archive` — дефект нашёлся только прогоном под
реальной ролью, потому что читать большой `switch` глазами бесполезно.

Никакой другой замер этого не показывает: операция нужна именно для того, чтобы
такие ветви были видны статически, до запуска.


"""
if "8.7 Трассировка решений о правах" not in text:
    if anchor_86 in text:
        text = text.replace(anchor_86, new_section + anchor_86, 1)
        changed = True
        print("добавлен подраздел 8.7 про трассировку прав")
    else:
        print("ВНИМАНИЕ: раздел 8.6 не найден")
else:
    print("подраздел 8.7 уже есть")

# --- 3. Подраздел про накопление и панель ------------------------------------
new_tail = """### 8.8 Накопление правок на длинных сессиях

Индекс обновляется не при каждом изменении, а по накоплению. Глубина пересбора
зависит от числа правок с момента последней индексации. Замерено на корпусе
из 124 файлов: индексация без графа свойств кода — 5,6 с, с ним — 20,8 с
(разница 3,7×), поэтому платить полную цену при каждой правке бессмысленно.

| Накоплено правок | Что выполняется | Почему так |
|---|---|---|
| 1–4 | быстрая переиндексация | граф вызовов и схема успевают обновиться за секунды |
| 5–19 | быстрая переиндексация (порог 5) | поиск и сверка схемы снова достоверны |
| 20 и больше | полный пересбор с графом свойств кода | межпроцедурные связи пересобираются |
| индекс старше 15 минут | полный пересбор | за это время структура могла уйти, даже при редких правках |

Пороги настраиваются для каждой разработки в её конфиге (секция `index`:
`reindex_after_changes`, `full_reindex_after_changes`, `reindex_interval_minutes`)
и через панель управления.

Агенту видно накопление в ответе любой операции: поле `accumulation` содержит
число правок с последней индексации, оба порога и возраст индекса. Поле
`threshold_reached` говорит, какой порог достигнут. Это не служебная мелочь:
признак нужен, чтобы понимать, насколько свежие факты приходят.

### 8.9 Панель управления

Настройки, размеры баз и статистика — в панели:

```powershell
python tools\\ragraf-admin.py
```

Открывается на `127.0.0.1:8777`, доступ только с этой машины. Панель показывает:
разработки и состояние их индексов, размеры баз и состав по таблицам, статистику
обращений и оценку экономии, качество индекса (размеры чанков, полноту сигнатур),
настройки порогов. Изменяющие запросы требуют токен доступа: он печатается при
запуске сервера.

**Когда идти в панель.** Если результат операции выглядит странно — сначала
смотреть `index_status` и блок `quality`: там видно, есть ли чанки сверх лимита,
сколько сигнатур обрезано и доступен ли векторный поиск. Проверять настройки
через файлы конфигов не нужно: панель правит их с резервной копией и проверкой
допустимых значений.
"""
if "8.8 Накопление правок" not in text:
    text = text.rstrip() + "\n\n" + new_tail
    changed = True
    print("добавлены подразделы 8.8 (накопление) и 8.9 (панель)")
else:
    print("подразделы 8.8/8.9 уже есть")

if not changed:
    print("\nизменений не требуется")
    raise SystemExit(0)

# --- резервная копия и запись в исходной кодировке ---------------------------
stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
backup = path.with_name(f"{path.name}.bak.{stamp}-ragraf-ops")
shutil.copy2(path, backup)
print(f"\nрезервная копия: {backup.name}")

payload = text.encode("utf-8")
if had_bom:
    payload = b"\xef\xbb\xbf" + payload
if crlf:
    payload = payload.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
path.write_bytes(payload)

after = path.read_bytes()
print(f"записано: {len(after)} байт, BOM={after.startswith(b'\xef\xbb\xbf')}, "
      f"CRLF={b'\r\n' in after}")
print(f"строк: {len(path.read_text(encoding='utf-8-sig').splitlines())}")
