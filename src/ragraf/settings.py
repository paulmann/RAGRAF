def external_overrides(path: str | Path | None = None) -> dict[str, Any]:
    """Значения внешнего доступа из файла, названного окружением.

    Источник нужен до открытия панели: в закрытом контуре панель может быть не
    запущена, а отображение групп и адрес приёмника проверить всё равно надо.
    Файл сильнее `catalog/settings.json` — так же, как остальные переменные
    RAGRAF сильнее файлов.

    Файл содержит ТОЛЬКО известные ключи: посторонние не попадают в настройки,
    иначе опечатка в имени ключа стала бы настройкой. Значение доступа в файле
    не хранится: для него есть переменная окружения, имя которой задаёт
    `siem_token_env`.
    """
    import os

    if not path:
        named = str(os.environ.get(EXTERNAL_CONFIG_ENV) or "").strip()
        if not named:
            return {}
        path = named
    target = Path(path)
    if not target.exists():
        return {}
    raw = util.read_json(target, default=None)
    if not isinstance(raw, dict):
        return {}
    nested = raw.get("settings")
    source = nested if isinstance(nested, dict) else raw
    return {key: source[key] for key in STORE_KEYS if key in source}


@dataclass
class SettingsState:
    """Текущее состояние настроек: глобальные и по каждой разработке."""

    global_settings: dict[str, Any] = field(default_factory=dict)
    per_project: dict[str, dict[str, Any]] = field(default_factory=dict)
    defaults: dict[str, Any] = field(default_factory=lambda: dict(DEFAULTS))
    editable: list[str] = field(default_factory=lambda: list(EDITABLE))
    descriptions: dict[str, str] = field(default_factory=lambda: dict(DESCRIPTIONS))
    bounds: dict[str, list[int]] = field(
        default_factory=lambda: {k: list(v) for k, v in BOUNDS.items()}
    )
    # Настройки-перечисления: интерфейс должен рисовать их списком,
    # а не числовым полем. Без этого значения вида «docs» попадали бы
    # в input type=number и редактирование ломалось бы.
    enums: dict[str, list[str]] = field(
        default_factory=lambda: {k: list(v) for k, v in ENUM_KEYS.items()}
    )
    # Перечень форматов данных: панель рисует по нему вкладку «Форматы»,
    # в том числе окно фильтра. Список приходит с сервера, а не хранится в
    # JavaScript: иначе реестр пришлось бы дублировать, и они разошлись бы.
    formats: list[dict[str, Any]] = field(default_factory=list)
    #: Сводка: сколько форматов и групп включено.
    formats_summary: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class SettingsStore:
    """Хранилище глобальных настроек: один JSON рядом с реестром.

    Файл отдельный от каталога разработок: настройки и описания разработок —
    разные сущности, и их слияние усложнило бы обе.
    """

    def __init__(self, path: Path | None = None) -> None:
        # Путь состояния выбирает `paths`: иначе прогон в песочнице пишет в
        # живой `catalog/settings.json` (измерено 30.10.2026, этап 7).
        self.path = Path(path) if path else paths.settings_path()

    def load(self) -> dict[str, Any]:
        """Прочитать настройки.

        ВНИМАНИЕ про структуру файла. `save()` записывает значения ВЛОЖЕННО:
        `{"version": 1, "settings": {...}}`. Первая версия `load()` читала ключи
        с ВЕРХНЕГО уровня, поэтому сохранённое значение не находилось, и чтение
        всегда возвращало значение по умолчанию. Дефект найден проверкой
        tools/check_admin.py: запись отвечала «сохранено», а чтение отдавало
        прежнее число.

        Здесь читаются оба варианта: вложенный (текущий формат) и плоский
        (совместимость с файлом, записанным ранней версией).
        """
        raw = util.read_json(self.path, default=None)
        if not isinstance(raw, dict):
            raw = {}
        # Значения могут лежать в разделе settings (текущий формат) либо на
        # верхнем уровне (ранние записи).
        nested = raw.get("settings")
        source: dict[str, Any] = nested if isinstance(nested, dict) else raw

        out = dict(DEFAULTS)
        # Читаются только известные ключи: посторонние значения из файла
        # не попадают в настройки, иначе опечатка в ключе стала бы настройкой.
        for key in STORE_KEYS:
            if key in source:
                out[key] = source[key]
            elif key in raw:
                out[key] = raw[key]
        return out

    def _stored(self) -> dict[str, Any]:
        """Что РЕАЛЬНО записано в файле, без умолчаний.

        Отдельно от `load()` намеренно: `load()` отдаёт слияние с умолчаниями
        и нужен читателю, а `save()` обязан вернуть в файл ровно то, что в нём
        было объявлено, плюс новое. Иначе одно сохранение материализует все
        ключи и умолчание начинает выглядеть заявлением.
        """
        raw = util.read_json(self.path, default=None)
        if not isinstance(raw, dict):
            return {}
        nested = raw.get("settings")
        source: dict[str, Any] = nested if isinstance(nested, dict) else raw
        return {key: source[key] for key in STORE_KEYS if key in source}

    def save(self, values: dict[str, Any]) -> dict[str, Any]:
        """Сохранить настройки, проверив значения. Возвращает сохранённое.

        Ошибочное значение не «исправляется молча»: возвращается причина,
        и администратор видит, что именно не принято.

        В файл попадают ТОЛЬКО явно заданные значения — те, что уже лежали
        в файле, и те, что переданы сейчас. Умолчания не записываются.
        Причина измерена 28.10.2026: прежняя редакция писала в файл слияние
        с умолчаниями, и одно действие панели (установка `ragraf_mode`)
        оставляло в файле все 57 ключей. После этого `edition: community`
        читался как ЯВНОЕ заявление владельца (`edition.declared_edition`),
        действующая лицензия pro понижалась до community, и три проверки
        лицензий краснели по чужой причине. Записанное умолчание перестаёт
        быть умолчанием — это и есть дефект, а не мелочь оформления.
        """
        clean = self.load()
        problems = validate(values, current=clean)
        if problems:
            raise ValueError("; ".join(problems))
        stored = self._stored()
        merged = dict(stored)
        for key, value in values.items():
            if key in STORE_KEYS:
                clean[key] = value
                merged[key] = value
        # Ничего не изменилось — файл не переписывается. Причина измерена
        # 28.10.2026 (задание И42): сохранение «ничего» сдвигало
        # `updated_at`, и метка обновления переставала отличать настоящую
        # правку от пустого нажатия. Значения при этом не терялись, но
        # признак «настройки менялись» становился ложным.
        if merged == stored:
            return clean
        util.write_json(
            self.path,
            {"version": 1, "settings": merged, "updated_at": util.now_iso()},
            indent=2,
        )
        return clean


def _check_formats(value: Any) -> list[str]:
    """Проверить значение `index_formats`. Возвращает причины отказа."""
    from . import formats as formats_mod

    if isinstance(value, str):
        if value.strip() == formats_mod.ALL:
            return []
        parts = [p.strip() for p in value.split(",") if p.strip()]
    elif isinstance(value, (list, tuple)):
        parts = [str(p).strip() for p in value]
    else:
        return ["«index_formats» принимает список идентификаторов форматов или «*»"]
    if not parts:
        # Пустой список — это «выключить всё». Такого состояния не бывает:
        # normalize превращает его в «все», и молча продолжать с пустым
        # значением значило бы обещать одно, а делать другое.
        return ["«index_formats»: пустой список недопустим — для всех форматов "
                "укажите «*»"]
    unknown = [p for p in parts if p != formats_mod.ALL and p not in formats_mod.BY_ID]
    if unknown:
        return [f"«index_formats»: неизвестные форматы {', '.join(sorted(unknown))}"]
    return []


def _check_group_roles(value: Any) -> list[str]:
    """Проверить отображение групп внешнего каталога на роли.

    Роль обязана быть из ЗАКРЫТОГО списка прав `access.SCOPES`. Иначе опечатка
    «amin» вместо «admin» прошла бы запись молча, и отображение выглядело бы
    настроенным, а права не выдавались бы никогда — отказ, который ищут в
    провайдере, а не в настройке.
    """
    from .access import SCOPES

    if isinstance(value, str):
        parts = [item for item in value.replace(";", ",").split(",")]
    elif isinstance(value, (list, tuple)):
        parts = [str(item) for item in value]
    else:
        return ["«sso_group_roles» принимает список записей «группа:роль»"]
    problems: list[str] = []
    for raw in parts:
        text = str(raw).strip()
        if not text:
            continue
        if ":" not in text:
            problems.append(
                f"«sso_group_roles»: запись «{text}» без роли — ожидается «группа:роль»"
            )
            continue
        group, role = text.split(":", 1)
        if not group.strip():
            problems.append(f"«sso_group_roles»: запись «{text}» без имени группы")
            continue
        if role.strip().lower() not in SCOPES:
            problems.append(
                f"«sso_group_roles»: роль «{role.strip()}» вне закрытого списка "
                f"{', '.join(SCOPES)} (запись «{text}»)"
            )
    return problems


def _check_agent_list(value: Any) -> list[str]:
    """Проверить список имён агентов: список или строка через запятую.

    Зачем терпимость к строке: из интерфейса значение приходит строкой, и
    отвергать её значило бы требовать JSON в поле ввода.
    """
    if isinstance(value, str):
        items = [part.strip() for part in value.split(",") if part.strip()]
    elif isinstance(value, (list, tuple, set)):
        items = [str(part).strip() for part in value if str(part).strip()]
    else:
        return ["«secrets_allowed_agents» принимает список имён или строку через запятую"]
    problems: list[str] = []
    for name in items:
        if " " in name:
            problems.append(f"«secrets_allowed_agents»: имя {name!r} содержит пробел")
        if len(name) > 200:
            problems.append(f"«secrets_allowed_agents»: имя длиннее 200 символов")
    if len(items) > 500:
        problems.append("«secrets_allowed_agents»: больше 500 имён")
    return problems


def validate(values: dict[str, Any], current: dict[str, Any] | None = None) -> list[str]:
    """Проверить значения настроек. Возвращает список причин отказа.

    Проверки обязательны: неверный порог тихо ломает поведение. Например,
    порог полного пересбора меньше порога быстрого означает, что быстрый режим
    никогда не сработает.

    Аргумент current — действующие значения (то, что уже записано). Он нужен
    для проверки согласованности при ЧАСТИЧНОЙ записи: если в запросе пришёл
    только порог полного пересбора, сравнивать его надо с уже сохранённым
    порогом быстрой. Без этого проверка проходила незаметно — дефект найден
    проверкой tools/check_admin_project_settings.py.
    """
    problems: list[str] = []
    for key, value in (values or {}).items():
        if key not in STORE_KEYS:
            problems.append(f"настройка «{key}» не поддерживается")
            continue
        # Список форматов проверяется по реестру, а не по типу значения:
        # опечатка `wind` вместо `word` иначе прошла бы молча и выключила
        # бы Word, ничего не сообщив.
        if key == "index_formats":
            problems.extend(_check_formats(value))
            continue
        if key in BOOLEAN_KEYS:
            if not isinstance(value, bool):
                problems.append(f"«{key}» принимает только да/нет")
            continue
        # Профиль исключений: список ИМЁН каталогов. Проверяется теми же
        # правилами, что и при индексации (src/ragraf/excludes.py): шаблоны,
        # слэши и `.ragraf` отклоняются здесь, а не при следующей сборке.
        if key == "secrets_allowed_agents":
            problems.extend(_check_agent_list(value))
            continue
        if key == "exclude_noisy_dirs":
            from .excludes import ExcludeError, normalize
            if not isinstance(value, str):
                problems.append(
                    f"«{key}» принимает только строку с именами через запятую"
                )
            else:
                try:
                    normalize(value)
                except ExcludeError as exc:
                    problems.append(f"«{key}»: {exc}")
            continue
        # Ключи-строки (внешний доступ) проверяются по типу и длине: числовой
        # диапазон к ним неприменим, и без этой ветви настройка получала бы
        # «принимает только целое число» — то есть была бы нерабочей.
        if key in STRING_KEYS:
            if not isinstance(value, str):
                problems.append(f"«{key}» принимает только строку")
            elif len(value) > 2048:
                problems.append(f"«{key}»: длина больше 2048 символов")
            continue
        if key == "sso_group_roles":
            problems.extend(_check_group_roles(value))
            continue
        # Настройки-перечисления: значение обязано быть из списка.
        # Проверка здесь, а не при индексации: ошибку в опечатке надо видеть
        # сразу в интерфейсе, а не получать исключение через час работы.
        if key in ENUM_KEYS:
            allowed = ENUM_KEYS[key]
            if str(value).lower() not in allowed:
                problems.append(
                    f"«{key}»: допустимо {', '.join(allowed)}, "
                    f"получено {value!r}"
                )
            continue
        try:
            number = int(value)
        except (TypeError, ValueError):
            problems.append(f"«{key}» принимает только целое число")
            continue
        low, high = BOUNDS.get(key, (0, 10**9))
        if not (low <= number <= high):
            problems.append(f"«{key}»: допустимо от {low} до {high}, получено {number}")

    # Согласованность порогов: иначе быстрый режим недостижим.
    # Недостающие значения берутся из действующих настроек.
    base = dict(current or {})
    base.update(values or {})
    fast = base.get("reindex_after_changes")
    full = base.get("full_reindex_after_changes")
    if fast is not None and full is not None:
        try:
            if int(full) <= int(fast):
                problems.append(
                    "порог полного пересбора должен быть больше порога быстрой "
                    f"переиндексации ({full} ≤ {fast})"
                )
        except (TypeError, ValueError):
            pass
    return problems


