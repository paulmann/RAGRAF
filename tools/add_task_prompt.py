"""Дополнение промпта: метка задачи и отчёт по задаче.

Владелец добавил возможность собирать статистику RAGRAF по ОДНОЙ задаче
(команда `/RAGRAF` в SagaAI). В промпте об этом надо написать: без описания
агент не будет передавать метку, и статистика задач не соберётся.

Что добавляется:
  1. зачем метка нужна (каждый вызов инструмента — отдельный процесс);
  2. как передавать (`RAGRAF_TASK` или аргумент `task`);
  3. операция `task_stats` и что она возвращает;
  4. примеры вывода.
"""

from __future__ import annotations

import pathlib
import shutil

TARGET = pathlib.Path(r"C:\Users\mvd.AMD5700X3D\.pi\agent\AGENTS.md")
text = TARGET.read_text(encoding="utf-8")
print(f"  файл: {TARGET}")
print(f"  строк до правки: {len(text.splitlines())}")

MARKER = "### 8.19 Метка задачи и отчёт по задаче"
if MARKER in text:
    print("  раздел уже есть")
    raise SystemExit(0)

SECTION = """
### 8.19 Метка задачи и отчёт по задаче

Статистику RAGRAF можно собирать не только по агенту, но и по **отдельной
задаче пользователя**. Это нужно для команды `/RAGRAF` в SagaAI: она
показывает, сколько работы выполнил индекс при решении текущей задачи.

#### Почему нужна метка

**Каждый вызов инструмента RAGRAF запускает отдельный процесс.** «Сессия
RAGRAF» — это один запуск процесса с идентификатором вида
`s<epoch_ms>-<pid>`, и она живёт доли секунды. С задачей пользователя такая
сессия не совпадает: одна задача порождает десятки процессов.

Поэтому задача помечается **меткой** — одним и тем же значением во всех
вызовах. Только так вызовы собираются вместе.

#### Как передать метку

| Способ | Когда применяется |
|---|---|
| Переменная `RAGRAF_TASK` | внешний инструмент (функция SagaAI, скрипт) |
| Аргумент `task` | вызов через MCP или функцию |
| Идентификатор треда | в SagaAI это значение подставляет команда `/RAGRAF` |

Особенность: переменная окружения действует на **все** вызовы внутри
процесса, который её выставил. Поэтому тот, кто её ставит, обязан снять
её после задачи — иначе метка «прилипнет» к последующим вызовам.
В SagaAI так и сделано: метка ставится перед вызовом и снимается в блоке
`finally`.

#### Операция `task_stats`

Возвращает **готовый markdown** — его можно показать пользователю как есть:

```
ragraf(operation="task_stats")            # все задачи
ragraf(operation="task_stats", task="id") # одна задача
```

Что в отчёте:

- обращений к индексу и число ошибок;
- фактов получено, из них со ссылкой `файл:строка` (доля проверяемых);
- объём ответов в символах и оценка токенов;
- сколько символов заменили чтение файлов (оценка строк кода);
- таблица по операциям: вызовы, факты, среднее время;
- список задач в журнале, если их несколько.

Отличие от `usage`: `usage` отдаёт числа структурой (для программной
обработки), `task_stats` — текстом (для показа человеку).

#### Что показывает отчёт на практике

```
### RAGRAF: работа по задаче「<id задачи>」

- обращений к индексу: **12**
- ошибок: **0**
- фактов получено: **30**, со ссылкой файл:строка — **30** (100%)
- объём ответов: **8856** символов (~2214 токенов, оценка)
- заменили чтение файлов: **8856** символов (~196 строк кода)

| операция | вызовов | фактов | среднее |
|---|---|---|---|
| search | 5 | 14 | 1529 мс |
| symbol | 4 | 8 | 6 мс |
```

Эти числа — измерение, а не оценка: они читаются из журнала. Оценкой
являются только токены (символы делятся на 4) и строки (на 45).

#### Фильтр по задаче в командной строке

```bash
python tools/ragraf.py -p <конфиг> usage --task "<метка>"
python tools/ragraf.py -p <конфиг> usage                 # по задачам всё
```

В сводке появляются разбивки `by_task` (по задачам) и отдельная строка
`(без задачи)` для вызовов без метки — так видно, что часть работы
осталась неразмеченной.

#### Как метка пишется в журнал

Добавление поля идёт догоняющей миграцией: прежние журналы не требуют
удаления, старые записи видны как `(без задачи)`. Проверено на живом
журнале корпуса z: 138 вызовов сохранены полностью.

Особенность фильтра: `--task "(без задачи)"` ищет не строку, а записи
с пустым полем (NULL). Такая же логика у фильтра `--agent unknown`.

"""

# Раздел вставляется после 8.18 — перед следующим разделом верхнего уровня.
import re  # noqa: E402

anchors = ["\n## 9.", "\n## 10.", "\n## 11."]
inserted = False
for anchor in anchors:
    if anchor in text:
        text = text.replace(anchor, SECTION + anchor, 1)
        print(f"  вставлено перед {anchor.strip()}")
        inserted = True
        break

if not inserted:
    matches = list(re.finditer(r"\n### 8\.(\d+)[^\n]*\n", text))
    if matches:
        last = matches[-1]
        tail = text[last.end():]
        next_h2 = tail.find("\n## ")
        if next_h2 >= 0:
            pos = last.end() + next_h2
            text = text[:pos] + SECTION + text[pos:]
            print(f"  вставлено после 8.{last.group(1)}")
            inserted = True
    if not inserted:
        text = text.rstrip() + "\n" + SECTION
        print("  вставлено в конец")

backup = TARGET.with_suffix(".md.bak-task")
shutil.copy2(TARGET, backup)
TARGET.write_text(text, encoding="utf-8", newline="\n")
after = TARGET.read_text(encoding="utf-8")
print(f"  строк после правки: {len(after.splitlines())}")

print()
print("  проверки:")
checks = [
    (MARKER in after, "раздел добавлен"),
    (after.count(MARKER) == 1, "раздел ровно один"),
    ("RAGRAF_TASK" in after, "описан способ передачи метки"),
    ("task_stats" in after, "описана операция отчёта"),
    ("(без задачи)" in after, "описаны записи без метки"),
    ("by_task" in after, "описана разбивка по задачам"),
    ("/RAGRAF" in after, "упомянута команда в SagaAI"),
]
for ok, label in checks:
    print(f"    [{'OK ' if ok else '--'}] {label}")
