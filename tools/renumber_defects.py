"""Перенумеровать дефекты в статье: две таблицы использовали пересекающиеся номера.

После добавления трёх новых дефектов RAGRAF (сканирование, порядок ревизий,
накопление экспортов) таблица RAGRAF стала 1–8, а таблица разработки по-прежнему
начиналась с 6 — номера пересекались, и ссылки в тексте указывали не туда.

Приводится к единой нумерации: RAGRAF — 1–8, разработка — 9–17.
"""

from __future__ import annotations

import pathlib
import re

ARTICLE = pathlib.Path(__file__).resolve().parents[1] / "docs" / "05_article" / "RAGRAF_ARTICLE.md"
text = ARTICLE.read_text(encoding="utf-8")

# 1. Перенумерация таблицы дефектов РАЗРАБОТКИ (было 6–14, стало 9–17).
dev_map = {6: 9, 7: 10, 8: 11, 9: 12, 10: 13, 11: 14, 12: 15, 13: 16, 14: 17}
start = text.find("| № | Дефект | Как найден | Последствие")
end = text.find("### Что из этого дал именно индекс")
if start < 0 or end < 0:
    print("не найдена таблица дефектов разработки")
    raise SystemExit(1)

block = text[start:end]
for old, new in sorted(dev_map.items(), reverse=True):
    block = block.replace(f"| {old} | **", f"| {new} | **")
text = text[:start] + block + text[end:]

# 2. Подписи диаграммы: узлы D6..D14 → D9..D17.
for old, new in sorted(dev_map.items(), reverse=True):
    text = text.replace(f"D{old}[", f"D{new}[")
text = text.replace('<sub>D</sub>', "D")
text = text.replace("(9 дефектов agreements)", "(9 дефектов agreements)")

# 3. Ссылки в тексте и разделах выводов.
text = text.replace("- **№14 предотвращён до написания кода:**", "- **№17 предотвращён до написания кода:**")
text = text.replace("- **№7 закрыт новой операцией:**", "- **№10 закрыт новой операцией:**")
text = text.replace("- **№6, №11, №12, №13 найдены проверками**,",
                    "- **№9, №14, №15, №16 найдены проверками**,")
text = text.replace("- **№10 — не дефект кода.**", "- **№13 — не дефект кода.**")

# 4. Таблица распределения по классам.
text = text.replace(
    "| Падение с понятной ошибкой | 3 | №7, №8, №10 |",
    "| Падение с понятной ошибкой | 3 | №10, №11, №13 |",
)
text = text.replace(
    "| **«Работает, но не так»** | **8** | №6, №11, №12, №13, №1, №4, №7(рев), №8(эксп) |",
    "| **«Работает, но не так»** | **8** | №6, №7, №8, №9, №14, №15, №16, №4 |",
)
text = text.replace("| Ухудшение качества выдачи | 3 | №2, №3, №5 |",
                    "| Ухудшение качества выдачи | 3 | №2, №3, №5 |")
text = text.replace("| Заблокированная работа | 2 | №9, №14 |",
                    "| Заблокированная работа | 2 | №12, №17 |")

# 5. Заголовок подраздела про дефекты RAGRAF: было 5, стало 8.
text = text.replace("### Дефекты RAGRAF (найдены полигоном)",
                    "### Дефекты RAGRAF (найдены полигоном и проверками механизма)")
text = text.replace("| Найдено замером (5 дефектов RAGRAF)", "| Найдено замером и проверками")

# 6. Ссылки на номера в разборе.
text = text.replace("**Разбор дефекта №1 — он показателен.**", "**Разбор дефекта №1 — он показателен.**")

ARTICLE.write_text(text, encoding="utf-8", newline="\n")

# Проверка: номера в таблицах не пересекаются.
nums_ragraf = [int(m) for m in re.findall(r"^\| (\d+) \| \*\*", text, re.MULTILINE)]
print("номера дефектов в статье:", nums_ragraf)
print("всего строк-дефектов:", len(nums_ragraf))
print("дубликаты:", sorted({n for n in nums_ragraf if nums_ragraf.count(n) > 1}) or "нет")
